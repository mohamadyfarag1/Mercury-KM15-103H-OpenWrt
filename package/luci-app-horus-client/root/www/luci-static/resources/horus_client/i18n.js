// never sends it to our endpoints at /cgi-bin/horus_* -- every one of them
// used to get denied by cgi_auth.sh for that reason alone. Mirror the SAME
// session id into a cookie scoped to /cgi-bin/ so it actually reaches them.
// SameSite=Strict is required, not cosmetic: it is what stops another site
// from driving authenticated requests at the router. See AI_AGENT_RULES.md
// rule 25. This runs at module load, before any view issues a fetch.
